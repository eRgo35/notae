/**
 * Open-source licenses, from Settings' About card: back and the title, then the notices of [NOTICES] (Notae's license
 * and the third-party ones, generated by cargo-about) as plain text in a scrolling column at most 720 dp wide, one
 * paragraph per item. Escape closes it, as Back does through the core.
 */
@Composable
fun LicensesScreen(onAction: (Action) -> Unit, modifier: Modifier = Modifier) {
    val c = NotaeTheme.colors
    val assets = LocalContext.current.assets
    val paragraphs = remember(assets) { readNotices(assets) }
    val keys = remember { FocusRequester() }
    LaunchedEffect(Unit) { keys.requestFocus() }
    BoxWithConstraints(
        modifier
            .fillMaxSize()
            .screenBackground(c.background)
            .onPreviewKeyEvent { event ->
                val close = event.type == KeyEventType.KeyDown && event.key == Key.Escape
                if (close) onAction(Action.CloseLicenses)
                close
            }
            .focusRequester(keys)
            .focusable(),
    ) {
        val narrow = maxWidth < 420.dp
        Column(Modifier.fillMaxSize().padding(start = 16.dp, top = 16.dp, end = 16.dp), verticalArrangement = collapsingGaps(12.dp)) {
            Row(Modifier.screenFade(), horizontalArrangement = Arrangement.spacedBy(8.dp), verticalAlignment = Alignment.CenterVertically) {
                IconButton(stringResource(R.string.licenses_back), painterResource(R.drawable.ic_arrow_back), { onAction(Action.CloseLicenses) })
                Text(stringResource(R.string.settings_licenses), color = c.foreground, fontSize = if (narrow) 26.sp else 32.sp, fontWeight = FontWeight.SemiBold)
            }
            Box(Modifier.weight(1f).fillMaxWidth().screenContent(c.background)) {
                val state = rememberLazyListState()
                LazyColumn(
                    Modifier.fillMaxSize(),
                    state = state,
                    contentPadding = PaddingValues(bottom = 16.dp),
                    verticalArrangement = Arrangement.spacedBy(12.dp),
                    horizontalAlignment = Alignment.CenterHorizontally,
                ) {
                    items(paragraphs) { paragraph ->
                        Text(
                            paragraph,
                            Modifier.widthIn(max = 720.dp).fillMaxWidth(),
                            color = c.foreground,
                            fontSize = 13.sp,
                            fontFamily = FontFamily.Monospace,
                        )
                    }
                }
                ListScrollbar(state, Modifier.align(Alignment.TopEnd))
            }
        }
    }
}

/** The notices in the app's assets, written by cargo-about (docs/engineering-standards.md). */
internal const val NOTICES = "third_party_licenses.txt"

/** The notices split at blank lines; none if the asset cannot be read, which a packaged app always can. */
private fun readNotices(assets: AssetManager): List<String> = try {
    assets.open(NOTICES).bufferedReader().use { it.readText() }.split(Regex("\n{2,}")).filter(String::isNotBlank)
} catch (error: IOException) {
    Log.w("Notae", "cannot read $NOTICES", error)
    emptyList()
}
